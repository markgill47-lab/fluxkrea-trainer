"""The ai-toolkit backend. FLUX.2, Klein and Krea 2 as one config-driven class.

v1 has two classes here, one subclassing the other, differing mostly in
which strings they put in a YAML file (doc 01). They collapse into this,
with the per-model differences in ``models.py`` where they can be read.

**Quirks carried forward from v1, each of which cost somebody an evening.**
They are not obvious from ai-toolkit's docs and they are not guessable:

* **``lr`` is the key that is read, not ``learning_rate``.** The train
  config derives ``unet_lr`` from ``lr`` and falls back to a near-zero
  1e-6 when it is missing, so a run configured only with
  ``learning_rate`` trains at a rate that looks like nothing happening.
  Both are written.
* **Caching is a dataset-level setting**, not a train-level one:
  ``cache_latents_to_disk`` and ``cache_text_embeddings`` live in the
  dataset block. Setting them under ``train`` silently does nothing, and
  the VAE and text encoder then stay resident and take the VRAM the
  transformer needed.
* **``skip_first_sample`` is a train key.** The ``sample_at_first`` key in
  the sample block is ignored by current upstream, and a baseline sample
  on a 12B model is slow and can produce NaN on an untrained network.
* **The arch strings are ``flux2_klein_4b`` / ``flux2_klein_9b``.** v1
  emits ``flux2_klein``, which does not exist.

New here: ``mask_path`` is threaded from the dataset into the generated
config, which is the one line the whole masking feature exists to produce
(doc 04).
"""

from __future__ import annotations

import os
import re
import threading
from pathlib import Path
from typing import Any

from .. import paths
from ..events import Emitter, Log, LossPoint, Progress, no_op, safe
from . import BackendError, BackendProgress, register
from .models import Model, UnknownModel
from .models import find as find_model
from .models import get as get_model
