from .spec import RunSpec, run_name as spec_run_name

#: ai-toolkit's entry point, relative to its checkout.
RUNNER = "run.py"

#: How many times each image is seen per epoch. v1's constant, kept: the
#: datasets here are small enough that one pass is not a meaningful epoch.
DEFAULT_REPEATS = 10

#: Only when neither a save interval nor a sample interval was given.
#: Checkpoints are hundreds of megabytes each, so this is deliberately not
#: small.
DEFAULT_SAVE_EVERY = 500

#: Written into every generated config, so nobody hand-edits an artifact.
HEADER = (
    "# Generated by FluxKrea Trainer from a RunSpec. Do not hand-edit:\n"
    "# this file is rewritten every time the job is submitted.\n"
    "# Change the spec, not the artifact.\n"
)


# --------------------------------------------------------------------------
# output parsing
# --------------------------------------------------------------------------

#: ai-toolkit reports progress in several shapes depending on where it is:
#: an explicit step line, a tqdm bar, or a percentage with counts.
STEP_PATTERNS = (
    re.compile(r"[Ss]tep[:\s]+(\d+)\s*/\s*(\d+)"),
    re.compile(r"\|\s*(\d+)\s*/\s*(\d+)\s*\["),
    re.compile(r"\d+%\|?\s*(\d+)\s*/\s*(\d+)"),
)

#: Scientific notation included - ai-toolkit prints ``loss: 3.698e-01``.
LOSS_PATTERN = re.compile(r"[Ll]oss[:\s=]+([0-9]*\.?[0-9]+(?:[eE][+-]?[0-9]+)?)")

#: Lines worth raising to warning, so a failing run is visible in a tail.
TROUBLE = ("Traceback", "CUDA out of memory", "RuntimeError", "torch.OutOfMemoryError")


class OutputParser:
    """Turns ai-toolkit's stdout into ``Progress`` and ``LossPoint`` events.

    Separate from the backend so it can be tested against captured output
    without launching anything - which matters, because every one of these
    patterns is a guess about somebody else's formatting.
    """

    def __init__(self, emit: Emitter, total: int = 0) -> None:
        self.emit = safe(emit)
        self.step = 0
        self.total = total
        self.loss: float | None = None

    def __call__(self, line: str) -> bool:
        """Handle one line. Returns True if the raw line need not be logged."""
        redrawn_bar = False

        for index, pattern in enumerate(STEP_PATTERNS):
            match = pattern.search(line)
            if match:
                step, total = int(match.group(1)), int(match.group(2))
                # A sampling or caching bar counts to its own total; only
                # accept one that matches the run we are actually tracking.
                if self.total and total != self.total:
                    break
                self.step, self.total = step, total or self.total
                self.emit(Progress(step=self.step, total=self.total, message="Training"))
                # Patterns 1 and 2 are tqdm redrawing itself. Suppressing
                # those keeps a log tail readable; an explicit "step: x/y"
                # line is worth keeping.
                redrawn_bar = index > 0
                break

        loss = LOSS_PATTERN.search(line)
        if loss:
            try:
                value = float(loss.group(1))
            except ValueError:
                value = None
            if value is not None:
                self.loss = value
                self.emit(LossPoint(step=self.step, value=value))

        if any(marker in line for marker in TROUBLE):
            self.emit(Log(line=line, level="error"))
            return True

        return redrawn_bar

    def progress(self) -> BackendProgress:
        return BackendProgress(step=self.step, total=self.total, message="Training")


